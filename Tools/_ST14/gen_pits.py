"""Write the pit prototypes (holes.rsi as objects you can fall into) with fixtures over the hole.

Usage: python gen_pits.py <repo root>

The sprite is centred on the entity. The fixtures are vertical runs of 8 px columns over the
hole, shrunk by a few px so the rim stays walkable; ST14PitSystem drops whoever's centre gets inside.
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(sys.argv[1])
RSI = ROOT / "Resources/Textures/_ST14/Decals/holes.rsi"
OUT = ROOT / "Resources/Prototypes/_ST14/Entities/Structures/Terrain/pits.yml"
COL = 8
SHRINK = 4  # px of the rim that does not count as the hole

HEADER = """# Generated by Tools/_ST14/gen_pits.py, edit the script instead.
# Holes you can fall into. Fixtures cover the hole minus its rim; ST14PitSystem makes whoever's centre
# gets inside fall like into a chasm.
- type: entity
  abstract: true
  id: ST14PitBase
  name: pit
  description: A deep hole in the ground. You can't see the bottom.
  placement:
    mode: SnapgridCenter
  components:
  - type: Transform
    anchored: true
  - type: Clickable
  - type: Sprite
    sprite: _ST14/Decals/holes.rsi
    drawdepth: FloorObjects
  - type: Icon
    sprite: _ST14/Decals/holes.rsi
  - type: Chasm
  - type: ST14Pit
  - type: Physics
    bodyType: Static
  - type: Tag
    tags:
    - HideContextMenu
"""


def runs(im):
    w, h = im.size
    # MinFilter erodes the alpha so the outer rim is left out.
    alpha = im.getchannel("A").point(lambda a: 255 if a > 128 else 0).filter(ImageFilter.MinFilter(SHRINK * 2 + 1))
    px = alpha.load()
    out = []
    for x0 in range(0, w, COL):
        x1 = min(x0 + COL, w)
        start = None
        for y in range(h + 1):
            full = y < h and sum(1 for x in range(x0, x1) if px[x, y]) * 2 >= (x1 - x0)
            if full and start is None:
                start = y
            elif not full and start is not None:
                out.append((x0, start, x1, y))
                start = None
    return out


def main():
    meta = json.loads((RSI / "meta.json").read_text(encoding="utf-8"))
    w, h = meta["size"]["x"], meta["size"]["y"]
    parts = [HEADER]
    states = [s["name"] for s in meta["states"]]
    for state in states:
        im = Image.open(RSI / f"{state}.png").convert("RGBA")
        fixtures = []
        for i, (x0, y0, x1, y1) in enumerate(runs(im)):
            l, r = (x0 - w / 2) / 32, (x1 - w / 2) / 32
            b, t = (h / 2 - y1) / 32, (h / 2 - y0) / 32
            fixtures.append(f"""      fix{i + 1}:
        shape:
          !type:PhysShapeAabb
          bounds: "{l:.5g},{b:.5g},{r:.5g},{t:.5g}"
        layer:
        - WallLayer
        mask:
        - ItemMask
        density: 1000
        hard: false""")
        parts.append(f"""
- type: entity
  parent: ST14PitBase
  id: ST14Pit{state[len("hole"):]}
  components:
  - type: Sprite
    state: {state}
  - type: Icon
    state: {state}
  - type: Fixtures
    fixtures:
{chr(10).join(fixtures)}
""")
    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")

    loc = {
        "en-US": ("pit", "A deep hole in the ground. You can't see the bottom."),
        "ru-RU": ("яма", "Глубокая дыра в земле. Дна не видно."),
    }
    for lang, (name, desc) in loc.items():
        lines = ["# Generated by Tools/_ST14/gen_pits.py\n", f"ent-ST14PitBase = {name}\n    .desc = {desc}\n"]
        lines += [f"\nent-ST14Pit{s[len('hole'):]} = {{ ent-ST14PitBase }}\n    .desc = {{ ent-ST14PitBase.desc }}\n" for s in states]
        (ROOT / f"Resources/Locale/{lang}/_ST14/entities/pits.ftl").write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(states)} pits -> {OUT}")


if __name__ == "__main__":
    main()
