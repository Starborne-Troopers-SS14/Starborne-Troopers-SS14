def fixture_yaml(index, box):
    l, b, r, t = box
    return f"""      fix{index}:
        shape:
          !type:PhysShapeAabb
          bounds: "{l:.5g},{b:.5g},{r:.5g},{t:.5g}"
        layer:
        - HighImpassable
        - MidImpassable
        - LowImpassable
        density: 1000"""


def main():
    states = [s["name"] for s in json.loads((RSI / "meta.json").read_text())["states"]]
    pieces = {}
    for state in states:
        im = Image.open(RSI / f"{state}.png").convert("RGBA")
        cw = canvas_width(im.getbbox())
        off_x = (cw / 2 - 16) / 32
        off_y = (FH / 2 - 16) / 32
        pieces[state] = (off_x, off_y, boxes(im, cw, off_x, off_y))

    parts = [HEADER]
    for state in states:
        off_x, off_y, bxs = pieces[state]
        fixtures = [fixture_yaml(i + 1, b) for i, b in enumerate(bxs)]
        parts.append(f"""
- type: entity
  parent: ST14WallRockBase
  id: {ident(state)}
  suffix: {SUFFIX.get(state, state)}
  components:
  - type: Sprite
    state: {state}
    offset: {off_x:g}, {off_y:g}
  - type: Icon
    state: {state}
  - type: Fixtures
    fixtures:
{chr(10).join(fixtures)}
""")

    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")

    for lang, (name, desc) in LOC.items():
        lines = ["# Generated by Tools/_ST14/gen_rock_wall_pieces.py\n",
                 f"ent-ST14WallRockBase = {name}\n    .desc = {desc}\n"]
        lines += [f"\nent-{ident(st)} = {{ ent-ST14WallRockBase }}\n    .desc = {{ ent-ST14WallRockBase.desc }}\n" for st in states]
        loc = ROOT / f"Resources/Locale/{lang}/_ST14/entities/rock-walls.ftl"
        loc.write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(states)} pieces -> {OUT}")


if __name__ == "__main__":
    main()
