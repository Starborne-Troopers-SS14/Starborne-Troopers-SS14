"""Write the rock wall piece prototypes (one entity per wall.rsi state) with grid offsets and hitboxes.

Usage: python gen_rock_wall_pieces.py <repo root>

wall.rsi frames are 128x224; every piece sits in a canvas 32/64/96/128 px wide, centred
horizontally and resting on the frame bottom. The sprite offset puts the canvas bottom-left
on the bottom-left of the entity's tile, so pieces snap together on the 32 px grid.
Hitboxes stop walkers and thrown items but not bullets or lasers (no Impassable, BulletImpassable or
Opaque layer). They are one box per 16 px column of the opaque silhouette, minus a few px at the bottom.
"""
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(sys.argv[1])
RSI = ROOT / "Resources/Textures/_ST14/Structures/Terrain/wall.rsi"
OUT = ROOT / "Resources/Prototypes/_ST14/Entities/Structures/Terrain/wall.yml"
FW, FH = 128, 224
STRIP = 16
BOTTOM_CUT = 14  # px of the piece bottom left walkable so a mob can stand right against the wall

HEADER = """# Generated by Tools/_ST14/gen_rock_wall_pieces.py, edit the script instead.
# One wall per piece of wall.rsi, sprites untouched. The entity stands on the bottom-left tile of the piece,
# so pieces placed on neighbouring tiles join without gaps. Hitboxes follow the piece outline in 16 px columns.
- type: entity
  abstract: true
  parent: BaseStructure
  id: ST14WallRockBase
  name: rock wall
  description: A sheer face of natural stone. Solid enough to build against.
  placement:
    mode: SnapgridCenter
  components:
  - type: Sprite
    sprite: _ST14/Structures/Terrain/wall.rsi
    drawdepth: Walls
  - type: Icon
    sprite: _ST14/Structures/Terrain/wall.rsi
  - type: Physics
    bodyType: Static
  - type: Tag
    tags:
    - Structure
"""


LOC = {
    "en-US": ("rock wall", "A sheer face of natural stone. Solid enough to build against."),
    "ru-RU": ("скальная стена", "Отвесная природная скала. Достаточно прочная, чтобы строить вплотную."),
}


def canvas_width(bbox):
    x0, _, x1, _ = bbox
    for cw in (32, 64, 96, 128):
        left = (FW - cw) // 2
        if x0 >= left - 1 and x1 <= left + cw + 1:
            return cw
    return 128


def boxes(im, cw, off_x, off_y):
    px = im.load()
    left = (FW - cw) // 2
    cols = []
    for sx in range(left, left + cw, STRIP):
        rows = [y for y in range(FH) if sum(1 for x in range(sx, sx + STRIP) if px[x, y][3] > 0) >= STRIP // 2]
        cols.append((sx, rows[0], rows[-1] + 1) if rows else None)

    merged = []
    for c in cols:
        if c and merged and merged[-1][1:] == c[1:] and merged[-1][0] + merged[-1][3] == c[0]:
            m = merged[-1]
            merged[-1] = (m[0], m[1], m[2], m[3] + STRIP)
        elif c:
            merged.append((c[0], c[1], c[2], STRIP))

    out = []
    for sx, y0, y1, w in merged:
        # A column lower than the cut (thin edge of a ridge) is left walkable.
        if y1 - y0 - BOTTOM_CUT < 4:
            continue
        # Frame pixels to entity-local tiles: frame centre is the entity centre plus the sprite offset.
        l = (sx - FW / 2) / 32 + off_x
        r = (sx + w - FW / 2) / 32 + off_x
        b = (FH / 2 - y1 + BOTTOM_CUT) / 32 + off_y
        t = (FH / 2 - y0) / 32 + off_y
        out.append((l, b, r, t))
    return out


def ident(state):
    return "ST14WallRock" + "".join(p.capitalize() for p in state.split("_"))


